  // Merge the S1 full-text index without replacing the pre-existing course index.
  if (!window.__FV_S1_FETCH_PATCHED) {
    window.__FV_S1_FETCH_PATCHED = true;
    const nativeFetch = window.fetch.bind(window);
    const scriptUrl = (document.currentScript && document.currentScript.src) || location.href;
    const extraIndexUrl = new URL('./cours/s1-search-index.json', scriptUrl).href;
    window.fetch = async function(input, init) {
      let url = '';
      try { url = typeof input === 'string' ? new URL(input, location.href).href : new URL(input.url, location.href).href; } catch (_) {}
      if (!/\/mediatheque\/cours\/search-index\.json(?:[?#]|$)/.test(url)) return nativeFetch(input, init);
      const basePromise = nativeFetch(input, init).catch(() => null);
      const extraPromise = nativeFetch(extraIndexUrl, { cache: 'no-store', credentials: 'same-origin' }).catch(() => null);
      const [baseResponse, extraResponse] = await Promise.all([basePromise, extraPromise]);
      let base = {}, extra = {};
      try { if (baseResponse && baseResponse.ok) base = await baseResponse.clone().json(); } catch (_) {}
      try { if (extraResponse && extraResponse.ok) extra = await extraResponse.json(); } catch (_) {}
      return new Response(JSON.stringify({ ...base, ...extra }), {
        status: 200,
        headers: { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store' }
      });
    };
  }

  // Embedded Word illustrations are kept inside their course and rendered from a private marker.
  function sitePrefix() {
    const p = location.pathname.replace(/\/index\.html$/i, '/');
    const marker='/mediatheque/'; const i=p.indexOf(marker);
    return i>0 ? p.slice(0,i) : '';
  }
  function imageUrl(value) {
    const v=String(value||'').trim();
    return v.startsWith('/') ? (sitePrefix()+v || v) : v;
  }
  function hydrateImages(root=document) {
    root.querySelectorAll && root.querySelectorAll('.course-content p').forEach(p => {
      const txt=(p.textContent||'').trim();
      const m=txt.match(/^\[\[image:([^|]+)\|([^\]]*)\]\]$/);
      if (!m) return;
      const fig=document.createElement('figure');
      fig.className='course-embedded-image';
      fig.style.cssText='margin:1.55rem 0;text-align:center';
      const img=document.createElement('img'); img.src=imageUrl(m[1]); img.alt=m[2]||'Illustration du cours';
      img.loading='lazy'; img.style.cssText='display:block;max-width:100%;height:auto;margin:0 auto;border-radius:6px';
      fig.appendChild(img); p.replaceWith(fig);
    });
  }
  function observeImages() {
    const target=document.querySelector('[data-course-content]');
    if (!target) return;
    hydrateImages(document);
    new MutationObserver(() => hydrateImages(document)).observe(target, { childList:true, subtree:true });
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', observeImages, { once:true }); else observeImages();
